Page({
  data: {
    articles: ARTICLES,
    filteredArticles: ARTICLES,
    categories: ['全部', '种植技术', '田间管理', '施肥技术', '病虫害防治', '收获储藏', '灌溉技术', '设施农业', '果树管理', '资源利用', '农机使用'],
    selectedCategory: '全部',
    searchKey: '',
    showArticle: false,
    currentArticle: {}
  },

  onLoad() {
    this.loadArticles();
  },

  loadArticles() {
    this.filterArticles();
  },

  selectCategory(e) {
    const category = e.currentTarget.dataset.category;
    this.setData({ selectedCategory: category });
    this.filterArticles();
  },

  onSearch(e) {
    const searchKey = e.detail.value;
    this.setData({ searchKey });
    this.filterArticles();
  },

  filterArticles() {
    let filtered = this.data.articles;

    if (this.data.selectedCategory !== '全部') {
      filtered = filtered.filter(a => a.category === this.data.selectedCategory);
    }

    if (this.data.searchKey) {
      const key = this.data.searchKey.toLowerCase();
      filtered = filtered.filter(a =>
        a.title.toLowerCase().includes(key) ||
        a.summary.toLowerCase().includes(key) ||
        a.tags.some(t => t.toLowerCase().includes(key))
      );
    }

    this.setData({ filteredArticles: filtered });
  },

  goToArticle(e) {
    const id = e.currentTarget.dataset.id;
    const article = this.data.articles.find(a => a.id === id);
    if (article) {
      this.setData({
        showArticle: true,
        currentArticle: article
      });
    }
  },

  closeArticle() {
    this.setData({ showArticle: false });
  },

  stopPropagation() {}
});
